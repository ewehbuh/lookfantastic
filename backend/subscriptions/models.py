from django.db import models
from django.conf import settings
from django.utils import timezone
from decimal import Decimal

class SubscriptionPlan(models.Model):
    """
    A subscription plan (e.g. Beauty Box Monthly).
    """
    INTERVAL_CHOICES = [
        ('month', 'Monthly'),
        ('quarter', 'Quarterly'),
        ('year', 'Annual'),
    ]
    name = models.CharField(max_length=100)
    slug = models.SlugField(max_length=120, unique=True)
    description = models.TextField()
    features = models.TextField(help_text="HTML or plain text list of box contents/features")
    price = models.DecimalField(max_digits=10, decimal_places=2)
    interval = models.CharField(max_length=20, choices=INTERVAL_CHOICES, default='month')
    interval_count = models.PositiveIntegerField(default=1, help_text="e.g. every 1 month")
    is_active = models.BooleanField(default=True)
    image = models.ImageField(upload_to='subscriptions/', blank=True, null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.name} – {self.price} / {self.interval}"


class UserSubscription(models.Model):
    """
    A user's active or past subscription.
    """
    STATUS_CHOICES = [
        ('active', 'Active'),
        ('cancelled', 'Cancelled'),
        ('paused', 'Paused'),
        ('expired', 'Expired'),
    ]
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='subscriptions')
    plan = models.ForeignKey(SubscriptionPlan, on_delete=models.PROTECT, related_name='subscriptions')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='active')
    start_date = models.DateTimeField(default=timezone.now)
    current_period_start = models.DateTimeField(default=timezone.now)
    current_period_end = models.DateTimeField()
    cancelled_at = models.DateTimeField(null=True, blank=True)
    next_billing_date = models.DateTimeField()
    # Optional: link to payment method
    # payment_method_id = models.CharField(max_length=100, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.user.email} – {self.plan.name} ({self.status})"

    def save(self, *args, **kwargs):
        if not self.current_period_end:
            # Calculate end date based on interval
            self.current_period_end = self.current_period_start + timezone.timedelta(days=30)
        if not self.next_billing_date:
            self.next_billing_date = self.current_period_end
        super().save(*args, **kwargs)


class SubscriptionOrder(models.Model):
    """
    A record of an order generated by the subscription (each recurring billing).
    """
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='subscription_orders')
    subscription = models.ForeignKey(UserSubscription, on_delete=models.CASCADE, related_name='orders')
    order_number = models.CharField(max_length=20, unique=True, editable=False)
    amount = models.DecimalField(max_digits=10, decimal_places=2)
    status = models.CharField(max_length=20, default='pending')
    created_at = models.DateTimeField(auto_now_add=True)

    def save(self, *args, **kwargs):
        if not self.order_number:
            import uuid
            self.order_number = uuid.uuid4().hex[:12].upper()
        super().save(*args, **kwargs)

    def __str__(self):
        return f"SubsOrder {self.order_number} - {self.user.email}"
